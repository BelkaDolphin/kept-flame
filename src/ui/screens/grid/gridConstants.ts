/**
 * 1 セルの基準サイズ(倍率 1.0 のときの CSS ピクセル)。【暫定・実機待ち】
 * GDD 6.6 の 44px 要件はこの値と {@link MIN_SCALE} の関係で保証する(下記)。
 */
export const CELL_SIZE_PX = 56;

/** GDD 6.6: 最小タップ領域 44px 角。 */
export const MIN_TAP_TARGET_PX = 44;

/**
 * 最小ズーム倍率。**「どれだけ縮小しても 1 セルのタップ領域が 44px 未満に
 * ならない」を式で保証する**(`CELL_SIZE_PX * MIN_SCALE >= MIN_TAP_TARGET_PX`)。
 * 44px 要件そのものは固定だが、CELL_SIZE_PX を実機計測で変えたら
 * この値は自動的に追随する。
 */
export const MIN_SCALE = MIN_TAP_TARGET_PX / CELL_SIZE_PX;

/** 最大ズーム倍率。【暫定・実機待ち】 */
export const MAX_SCALE = 3;

/**
 * 既定ズーム倍率(起動時の初期表示)。【暫定・実機待ち・#9b 確定でこの値だけ差し替える】
 * 6×8 格子が 1 画面に収まりやすい倍率という以上の根拠は無い。
 */
export const DEFAULT_SCALE = 1;

/**
 * タップ/ドラッグ(パン)を判別する移動しきい値(px・スクリーン座標)。
 * これを超えて動いたポインタは「パン」として扱いタップ候補から外す。
 */
export const TAP_MOVE_THRESHOLD_PX = 10;

/** タップと判定する最大保持時間(ms)。長押しはタップとして扱わない。 */
export const TAP_MAX_DURATION_MS = 500;
