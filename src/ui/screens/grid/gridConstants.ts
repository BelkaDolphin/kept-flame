// ピンチズーム/パン対応」。ここに置く値はすべて**実機(#9b・M19 で確定)待ちの暫定値**
// であり、M19 の「既定ズーム倍率は定数1箇所に隔離する」規律をそのまま踏襲する
// (`docs/MVP実装ロードマップ.md` M19 行)。**変更する場合はこのファイルの値だけを
